def validate_reasoning_synthesis(raw_text: str) -> Tuple[Optional[StructuredReasoningSynthesis], List[str]]:
    """
    Strictly validates raw Hermes text output against schema constraints.
    Returns (synthesis, errors).
    """
    errors: List[str] = []
    cleaned = raw_text.strip()

    # Strip markdown code blocks if present
    if "```" in cleaned:
        match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", cleaned)
        if match:
            cleaned = match.group(1).strip()

    try:
        data = json.loads(cleaned)
    except Exception as ex:
        return None, [f"JSON Parse Error: Malformed JSON ({str(ex)})"]

    if not isinstance(data, dict):
        return None, ["Schema Error: Root JSON output must be an object/dict."]

    # 1. Validate required string: what_is_happening
    if "what_is_happening" not in data:
        errors.append("Missing required field: 'what_is_happening'.")
    elif not isinstance(data["what_is_happening"], str) or not data["what_is_happening"].strip():
        errors.append("Field 'what_is_happening' must be a non-empty string.")

    # 2. Validate list fields
    list_fields = [
        "evidence_summary",
        "inferences",
        "predictions",
        "uncertainties",
        "what_would_change_assessment",
        "recommendations",
    ]
    for f in list_fields:
        if f in data and not isinstance(data[f], list):
            errors.append(f"Field '{f}' must be a list of strings, got {type(data[f]).__name__}.")
        elif f in data and isinstance(data[f], list):
            for i, item in enumerate(data[f]):
                if not isinstance(item, str):
                    errors.append(f"Field '{f}[{i}]' must be a string, got {type(item).__name__}.")

    # 3. Validate boolean field: requires_follow_up (optional, defaults to False)
    if "requires_follow_up" in data and not isinstance(data["requires_follow_up"], bool):
        errors.append(f"Field 'requires_follow_up' must be a boolean (true/false), got {type(data['requires_follow_up']).__name__}.")

    # 4. Validate categorical enum fields
    valid_urgencies = {e.value for e in UrgencyLevel}
    if "urgency" not in data:
        errors.append("Missing required field: 'urgency'.")
    elif not isinstance(data["urgency"], str) or data["urgency"].lower() not in valid_urgencies:
        errors.append(f"Field 'urgency' must be one of {sorted(list(valid_urgencies))}, got '{data.get('urgency')}'.")

    valid_actionabilities = {e.value for e in ActionabilityLevel}
    if "actionability" not in data:
        errors.append("Missing required field: 'actionability'.")
    elif not isinstance(data["actionability"], str) or data["actionability"].lower() not in valid_actionabilities:
        errors.append(f"Field 'actionability' must be one of {sorted(list(valid_actionabilities))}, got '{data.get('actionability')}'.")

    valid_relevances = {e.value for e in RelevanceLevel}
    if "relevance" not in data:
        errors.append("Missing required field: 'relevance'.")
    elif not isinstance(data["relevance"], str) or data["relevance"].lower() not in valid_relevances:
        errors.append(f"Field 'relevance' must be one of {sorted(list(valid_relevances))}, got '{data.get('relevance')}'.")

    # 4b. evidence_strength — OPTIONAL from Hermes (PI calculates it independently)
    #     If Hermes provides it, validate format but don't require it.
    valid_strengths = {e.value for e in EvidenceStrength}
    if "evidence_strength" in data:
        if not isinstance(data["evidence_strength"], str) or data["evidence_strength"].lower() not in valid_strengths:
            errors.append(f"Field 'evidence_strength' if provided must be one of {sorted(list(valid_strengths))}, got '{data.get('evidence_strength')}'.")

    # 5. Numerical confidence check: strictly disallow numerical confidence outputs
    if "confidence" in data:
        errors.append("Numerical confidence values are prohibited. Field 'confidence' is prohibited in Hermes output. Personal Intelligence calculates evidence strength deterministically.")

    # 6. Policy decision constraint: strictly disallow Hermes from dictating intervention actions
    if "action" in data and str(data["action"]).upper() in {"INTERRUPT", "BRIEFING", "DEFER", "SUPPRESS", "DISCARD"}:
        errors.append("Intervention decisions (INTERRUPT/BRIEFING/DEFER/SUPPRESS/DISCARD) belong strictly to InterventionPolicyEngine, not Hermes.")
    if "intervention_decision" in data or "policy_decision" in data:
        errors.append("Intervention policy decisions belong strictly to Personal Intelligence, not Hermes.")

    # 7. Database mutations constraint: strictly disallow Hermes from dictating database mutations
    if "database_mutations" in data or "mutations" in data or "state_mutations" in data:
        errors.append("Database mutations are prohibited in Hermes output. Personal Intelligence manages all persistent world model state.")

    if errors:
        return None, errors

    try:
        synthesis = StructuredReasoningSynthesis.from_dict(data)
        return synthesis, []
    except Exception as ex:
        return None, [f"Instantiation Error: {str(ex)}"]



