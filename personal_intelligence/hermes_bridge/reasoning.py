@dataclass
class ReasoningWorkflowResult:
    """Result of a complete reasoning workflow execution."""
    episode: ReasoningEpisode
    synthesis: StructuredReasoningSynthesis
    bounded_context: BoundedReasoningContext
    raw_response: str
    attempts: int = 1
    validation_errors: List[str] = field(default_factory=list)
    is_unparseable: bool = False

    @property
    def success(self) -> bool:
        """Returns True if reasoning completed successfully without validation failure."""
        return not self.is_unparseable and len(self.validation_errors) == 0


class ReasoningWorkflow:
    """
    Hardened situational reasoning workflow orchestrating bounded context construction,
    strict validation, targeted retries, safe fallbacks, and comprehensive audit logging.
    """

    def __init__(
        self,
        context_builder: Optional[ContextBuilder] = None,
        episode_store: Optional[EpisodeStore] = None,
        hermes_client: Optional[HermesClient] = None,
        max_retries: int = 2,
    ) -> None:
        self.context_builder = context_builder or ContextBuilder()
        self.episode_store = episode_store or EpisodeStore()
        self.hermes_client = hermes_client or HermesClient()
        self.max_retries = max_retries

    def run_workflow(
        self,
        situation: Situation,
        current_state: StateRepresentation,
        timeline: Optional[Timeline] = None,
        goals: Optional[List[Goal]] = None,
        patterns: Optional[List[LearnedPattern]] = None,
        episodes: Optional[List[Any]] = None,
        objective: Optional[str] = None,
    ) -> ReasoningWorkflowResult:
        """
        Executes end-to-end reasoning cycle with strict schema validation and retries.
        Never silently discards failures and never raises unhandled exceptions to caller.
        """
        now = datetime.now(timezone.utc)

        # 1. Build bounded reasoning context
        bounded_ctx = self.context_builder.build_bounded_context(
            situation=situation,
            current_state=current_state,
            timeline=timeline,
            goals=goals,
            patterns=patterns,
            episodes=episodes,
            objective=objective,
        )

        task_desc = objective or f"Reasoning investigation for {situation.type}"

        # 2. Create initial ReasoningEpisode record
        episode = self.episode_store.create_episode(
            trigger_type="situation_reasoning",
            situation_id=situation.id,
            metadata={
                "task": task_desc,
                "context_id": bounded_ctx.context_id,
            },
        )

        # 3. Retry loop (up to max_retries)
        last_raw_response = ""
        last_errors: List[str] = []
        tools_used: List[str] = []
        total_duration_ms = 0
        synthesis: Optional[StructuredReasoningSynthesis] = None
        attempt = 0

        while attempt <= self.max_retries:
            attempt += 1

            if attempt == 1:
                prompt = self._format_initial_prompt(bounded_ctx)
            else:
                prompt = self._format_retry_prompt(bounded_ctx, last_raw_response, last_errors, attempt)

            request = HermesInvocationRequest(
                prompt=prompt,
                session_id=episode.episode_id,
                skills=["personal_investigation"],
                timeout_seconds=60,
            )

            try:
                response = self.hermes_client.invoke_reasoning(request)
                last_raw_response = response.raw_response or ""
                total_duration_ms += response.duration_ms or 0
                if response.tools_executed:
                    tools_used.extend(response.tools_executed)
            except Exception as client_ex:
                last_raw_response = f"[Hermes Client Exception]: {str(client_ex)}"
                last_errors = [f"Client Invocation Exception: {str(client_ex)}"]
                continue

            # Validate response
            parsed_synthesis, errors = validate_reasoning_synthesis(last_raw_response)
