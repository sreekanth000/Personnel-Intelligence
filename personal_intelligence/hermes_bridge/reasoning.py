class UrgencyLevel(str, Enum):
    """Categorical urgency classification."""
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class ActionabilityLevel(str, Enum):
    """Categorical actionability rating."""
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class RelevanceLevel(str, Enum):
    """Categorical relevance rating."""
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class EvidenceStrength(str, Enum):
    """Categorical evidence strength classification.

    Blueprint §23: Personal Intelligence calculates evidence strength
    deterministically. Hermes does NOT generate it.
    """
    WEAK = "weak"
    MODERATE = "moderate"
    STRONG = "strong"
    CONFLICTED = "conflicted"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"


@dataclass
class BoundedReasoningRequest:
    """
    Standardized bounded reasoning request submitted to Hermes.
    Hermes reasons over this explicit bounded slice rather than receiving raw world model dumps.
    """
    situation: str
    observed_facts: List[str] = field(default_factory=list)
    evidence: List[str] = field(default_factory=list)
    known_patterns: List[str] = field(default_factory=list)
    active_goals: List[str] = field(default_factory=list)
    relevant_timeline: List[str] = field(default_factory=list)
    information_gaps: List[str] = field(default_factory=list)
    evidence_strength: str = "moderate"
    attention_state: str = "available"
    instructions: str = (
        "Reason strictly over the provided bounded context. Do not invent facts, extrapolate unauthorized certainty, "
        "or output numerical confidence percentages. Return structured JSON matching the required schema."
    )

    def __post_init__(self) -> None:
        self.validate()

    def validate(self) -> None:
        if not self.situation or not isinstance(self.situation, str):
            raise ValueError("situation must be a non-empty string.")
        for field_name in ["observed_facts", "evidence", "known_patterns", "active_goals", "relevant_timeline", "information_gaps"]:
            val = getattr(self, field_name)
            if not isinstance(val, list):
                raise ValueError(f"{field_name} must be a list of strings.")

    def to_dict(self) -> Dict[str, Any]:
        return {
            "situation": self.situation,
            "observed_facts": self.observed_facts,
            "evidence": self.evidence,
            "known_patterns": self.known_patterns,
            "active_goals": self.active_goals,
            "relevant_timeline": self.relevant_timeline,
            "information_gaps": self.information_gaps,
            "evidence_strength": self.evidence_strength,
            "attention_state": self.attention_state,
            "instructions": self.instructions,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "BoundedReasoningRequest":
        if not isinstance(data, dict):
            raise ValueError("Expected dictionary for BoundedReasoningRequest.")
        return cls(
            situation=data.get("situation", ""),
            observed_facts=data.get("observed_facts", []),
            evidence=data.get("evidence", []),
            known_patterns=data.get("known_patterns", []),
            active_goals=data.get("active_goals", []),
            relevant_timeline=data.get("relevant_timeline", []),
            information_gaps=data.get("information_gaps", []),
            evidence_strength=data.get("evidence_strength", "moderate"),
            attention_state=data.get("attention_state", "available"),
            instructions=data.get("instructions", ""),
        )


@dataclass
class StructuredReasoningSynthesis:
    """
    Structured synthesis generated by Hermes answering situational reasoning questions.
    Uses strictly categorical assessments without numerical confidence probabilities.
    """
    what_is_happening: str
    evidence_summary: List[str] = field(default_factory=list)
    inferences: List[str] = field(default_factory=list)
    predictions: List[str] = field(default_factory=list)
    uncertainties: List[str] = field(default_factory=list)
    what_would_change_assessment: List[str] = field(default_factory=list)
    recommendations: List[str] = field(default_factory=list)
    requires_follow_up: bool = False
    urgency: str = UrgencyLevel.MEDIUM.value
    actionability: str = ActionabilityLevel.MEDIUM.value
    relevance: str = RelevanceLevel.MEDIUM.value
    evidence_strength: str = EvidenceStrength.MODERATE.value  # PI-calculated, not Hermes-generated

    def __post_init__(self) -> None:
        self.validate()

    def validate(self) -> None:
        """Strict validation of synthesis fields."""
        if not self.what_is_happening or not isinstance(self.what_is_happening, str):
            raise ValueError("what_is_happening must be a non-empty string.")

        valid_urgencies = {e.value for e in UrgencyLevel}
        if str(self.urgency).lower() not in valid_urgencies:
            raise ValueError(f"Invalid urgency '{self.urgency}', must be one of {valid_urgencies}")
        self.urgency = str(self.urgency).lower()

        valid_actionabilities = {e.value for e in ActionabilityLevel}
        if str(self.actionability).lower() not in valid_actionabilities:
            raise ValueError(f"Invalid actionability '{self.actionability}', must be one of {valid_actionabilities}")
        self.actionability = str(self.actionability).lower()

        valid_relevances = {e.value for e in RelevanceLevel}
        if str(self.relevance).lower() not in valid_relevances:
            raise ValueError(f"Invalid relevance '{self.relevance}', must be one of {valid_relevances}")
        self.relevance = str(self.relevance).lower()

        valid_strengths = {e.value for e in EvidenceStrength}
        if str(self.evidence_strength).lower() not in valid_strengths:
            raise ValueError(f"Invalid evidence_strength '{self.evidence_strength}', must be one of {valid_strengths}")
        self.evidence_strength = str(self.evidence_strength).lower()

    def to_dict(self) -> Dict[str, Any]:
        """Serializes synthesis to dictionary."""
        return {
            "what_is_happening": self.what_is_happening,
            "evidence_summary": self.evidence_summary,
            "inferences": self.inferences,
            "predictions": self.predictions,
            "uncertainties": self.uncertainties,
            "what_would_change_assessment": self.what_would_change_assessment,
            "recommendations": self.recommendations,
            "requires_follow_up": self.requires_follow_up,
            "urgency": self.urgency,
            "actionability": self.actionability,
            "relevance": self.relevance,
            "evidence_strength": self.evidence_strength,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "StructuredReasoningSynthesis":
        """Constructs StructuredReasoningSynthesis from dictionary."""
        if not isinstance(data, dict):
            raise ValueError("Expected dictionary for StructuredReasoningSynthesis.")

        return cls(
            what_is_happening=data.get("what_is_happening", ""),
            evidence_summary=data.get("evidence_summary", []),
            inferences=data.get("inferences", []),
            predictions=data.get("predictions", []),
            uncertainties=data.get("uncertainties", []),
            what_would_change_assessment=data.get("what_would_change_assessment", []),
            recommendations=data.get("recommendations", []),
            requires_follow_up=bool(data.get("requires_follow_up", False)),
            urgency=str(data.get("urgency", "medium")).lower(),
            actionability=str(data.get("actionability", "medium")).lower(),
            relevance=str(data.get("relevance", "medium")).lower(),
            evidence_strength=str(data.get("evidence_strength", "moderate")).lower(),
        )



